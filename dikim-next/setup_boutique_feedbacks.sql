-- RLS
ALTER TABLE boutique_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE feedbacks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read boutique" ON boutique_items;
CREATE POLICY "Allow public read boutique" ON boutique_items
  FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Allow admin insert boutique" ON boutique_items;
CREATE POLICY "Allow admin insert boutique" ON boutique_items
  FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Allow admin update boutique" ON boutique_items;
CREATE POLICY "Allow admin update boutique" ON boutique_items
  FOR UPDATE TO authenticated USING (true);

DROP POLICY IF EXISTS "Allow admin delete boutique" ON boutique_items;
CREATE POLICY "Allow admin delete boutique" ON boutique_items
  FOR DELETE TO authenticated USING (true);

DROP POLICY IF EXISTS "Allow public read published feedbacks" ON feedbacks;
CREATE POLICY "Allow public read published feedbacks" ON feedbacks
  FOR SELECT TO public USING (is_published = true);

DROP POLICY IF EXISTS "Allow admin read all feedbacks" ON feedbacks;
CREATE POLICY "Allow admin read all feedbacks" ON feedbacks
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "Allow admin insert feedbacks" ON feedbacks;
CREATE POLICY "Allow admin insert feedbacks" ON feedbacks
  FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Allow admin update feedbacks" ON feedbacks;
CREATE POLICY "Allow admin update feedbacks" ON feedbacks
  FOR UPDATE TO authenticated USING (true);

DROP POLICY IF EXISTS "Allow admin delete feedbacks" ON feedbacks;
CREATE POLICY "Allow admin delete feedbacks" ON feedbacks
  FOR DELETE TO authenticated USING (true);
