-- Boutique items + homepage guest feedbacks
-- Run in Supabase → SQL Editor
-- ============================================================

-- Boutique products (shown on /mall)
CREATE TABLE IF NOT EXISTS boutique_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL DEFAULT 'Boutique item',
    image_path TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Guest feedbacks / reviews (shown on homepage #review)
CREATE TABLE IF NOT EXISTS feedbacks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_name TEXT NOT NULL,
    message TEXT NOT NULL,
    rating NUMERIC(2, 1) NOT NULL DEFAULT 5.0 CHECK (rating >= 1 AND rating <= 5),
    photo_path TEXT DEFAULT '/images/about.jpg',
    is_published BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

